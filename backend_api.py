#!/usr/bin/env python3
"""Small local backend/API for processed traffic-system outputs.

It serves the existing dashboard and exposes JSON generated by
integrated_traffic_system.py. It intentionally avoids a new web framework.
"""

from __future__ import annotations

import argparse
import json
from http.server import SimpleHTTPRequestHandler, ThreadingHTTPServer
from pathlib import Path
from urllib.parse import urlparse


class TrafficAPIHandler(SimpleHTTPRequestHandler):
    output_dir = Path("outputs/final_verify")

    def _send_json(self, payload, status=200):
        body = json.dumps(payload, indent=2).encode("utf-8")
        self.send_response(status)
        self.send_header("Content-Type", "application/json")
        self.send_header("Content-Length", str(len(body)))
        self.end_headers()
        self.wfile.write(body)

    def do_GET(self):
        parsed = urlparse(self.path)
        if parsed.path == "/api/latest":
            return self._send_json(self._load_latest())
        if parsed.path.startswith("/api/output/"):
            name = Path(parsed.path.replace("/api/output/", "")).name
            if name not in {
                "summary.json",
                "frames.json",
                "tracks.json",
                "lanes.json",
                "secondary_detections.json",
                "signal_decisions.json",
                "violations.json",
                "challans.json",
                "integrated_report.json",
            }:
                return self._send_json({"error": "Unsupported output file"}, 404)
            path = self.output_dir / name
            if not path.exists():
                return self._send_json({"error": f"Missing {name}"}, 404)
            return self._send_json(json.load(open(path, encoding="utf-8")))
        return super().do_GET()

    def _load_latest(self):
        def load(name, fallback):
            path = self.output_dir / name
            return json.load(open(path, encoding="utf-8")) if path.exists() else fallback

        return {
            "summary": load("summary.json", {}),
            "violations": load("violations.json", []),
            "challans": load("challans.json", []),
            "signals": load("signal_decisions.json", []),
            "lanes": load("lanes.json", {}),
            "tracks": load("tracks.json", []),
            "secondary_detections": load("secondary_detections.json", []),
        }


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--output-dir", default="outputs/final_verify")
    parser.add_argument("--host", default="127.0.0.1")
    parser.add_argument("--port", type=int, default=8765)
    args = parser.parse_args()

    TrafficAPIHandler.output_dir = Path(args.output_dir)
    server = ThreadingHTTPServer((args.host, args.port), TrafficAPIHandler)
    print(f"Serving dashboard/API at http://{args.host}:{args.port}/dashboard.html")
    print(f"Using output dir: {TrafficAPIHandler.output_dir}")
    server.serve_forever()


if __name__ == "__main__":
    main()
